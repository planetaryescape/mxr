#!/usr/bin/env bash

set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
script="${root}/scripts/check_lockfile_versions.sh"
tmp="$(mktemp -d)"
trap 'rm -rf "${tmp}"' EXIT

fail() {
  echo "check_lockfile_versions_test: $*" >&2
  exit 1
}

# $1 = workspace version; the rest are lock entries as name:version[:registry].
write_workspace() {
  local version="$1"
  shift
  printf '[workspace]\nmembers = []\n\n[workspace.package]\nversion = "%s"\nedition = "2021"\n' \
    "${version}" > Cargo.toml
  printf '# This file is automatically @generated by Cargo.\nversion = 4\n' > Cargo.lock
  local entry name package_version registry
  for entry in "$@"; do
    IFS=: read -r name package_version registry <<< "${entry}"
    printf '\n[[package]]\nname = "%s"\nversion = "%s"\n' "${name}" "${package_version}" >> Cargo.lock
    if [[ -n "${registry}" ]]; then
      printf 'source = "registry+https://github.com/rust-lang/crates.io-index"\n' >> Cargo.lock
    else
      # As in a real lock, unchanged lines between entries let git merge a
      # version bump next to a newly added entry.
      printf 'dependencies = [\n "serde",\n]\n' >> Cargo.lock
    fi
  done
}

commit_all() {
  git add -A
  git commit -q -m "$1"
}

mkdir -p "${tmp}/repo"
cd "${tmp}/repo"
git init -q -b main
git config user.email "ci@example.test"
git config user.name "CI"

# In-repo packages at the workspace version pass; registry packages and the
# vendored hnsw_rs keep versions of their own.
write_workspace 0.6.1 mxr:0.6.1 mxr-core:0.6.1 serde:1.0.200:registry hnsw_rs:0.3.4
output="$(bash "${script}")" || fail "a consistent lock was refused: ${output}"

# One in-repo package behind is refused, by name.
write_workspace 0.6.2 mxr:0.6.2 mxr-core:0.6.1
if output="$(bash "${script}" 2>&1)"; then
  fail "a stale in-repo package passed"
fi
grep -q "mxr-core 0.6.1" <<< "${output}" || fail "the stale package was not named: ${output}"
grep -q "mxr 0.6.2" <<< "${output}" && fail "a current package was named: ${output}"

# The race: a branch adds a crate, then a release bumps main before it merges.
write_workspace 0.6.1 mxr:0.6.1 mxr-core:0.6.1
commit_all "base"
git checkout -q -b add-crate
write_workspace 0.6.1 mxr:0.6.1 mxr-core:0.6.1 mxr-new:0.6.1
commit_all "feat: a new crate"
git checkout -q main
write_workspace 0.6.2 mxr:0.6.2 mxr-core:0.6.2
commit_all "chore(main): release 0.6.2"
git checkout -q add-crate

output="$(bash "${script}")" || fail "the branch on its own should pass: ${output}"
if output="$(bash "${script}" --merge-with main 2>&1)"; then
  fail "the merge with a newer release passed"
fi
grep -q "mxr-new 0.6.1" <<< "${output}" || fail "the new crate was not named: ${output}"

# After a rebase and a lock refresh the merge passes.
git rebase -q main
write_workspace 0.6.2 mxr:0.6.2 mxr-core:0.6.2 mxr-new:0.6.2
commit_all "chore: refresh the lock"
output="$(bash "${script}" --merge-with main)" || fail "a refreshed branch was refused: ${output}"

# A branch that does not merge cleanly is told to rebase.
git checkout -q -b conflicting main~1
write_workspace 0.6.9 mxr:0.6.9 mxr-core:0.6.9
commit_all "a conflicting version"
if output="$(bash "${script}" --merge-with main 2>&1)"; then
  fail "a conflicting merge passed"
fi
grep -q "rebase first" <<< "${output}" || fail "a conflict did not ask for a rebase: ${output}"
grep -q "Cargo.toml" <<< "${output}" || fail "the conflicted file was not named: ${output}"

echo "check_lockfile_versions_test: ok"
