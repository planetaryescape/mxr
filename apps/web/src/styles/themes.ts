const HEADER = `/*
 * GENERATED by \`npm run gen:themes\` from styles/themes.ts. Do not edit by
 * hand: change the theme's inputs there and regenerate. CI fails when this
 * file is stale.
 */
`;

/** Roles that start a new group in the output, so the file reads as the old hand-written blocks did. */
const GROUP_STARTS = new Set([
  "background",
  "muted",
  "border",
  "primary",
  "destructive",
  "unread-marker",
  "sidebar",
  "chart-1",
]);

function declarations(roles: Roles): string {
  return [...roles]
    .map(([name, value]) => `${GROUP_STARTS.has(name) ? "\n" : ""}  --${name}: ${value};`)
    .join("\n");
}

const wrap = (text: string) =>
  text
    .match(/.{1,74}(\s|$)/g)!
    .map((line) => ` * ${line.trim()}`)
    .join("\n");

/** The complete generated stylesheet: one block per theme, then each theme's contrast-increased block. */
export function renderThemesCss(themes: readonly ThemeInput[] = THEMES): string {
  const blocks = themes.map((theme) => {
    const comment = `/*\n${wrap(theme.note)}\n */`;
    return `${comment}\n${theme.selectors.join(",\n")} {\n  color-scheme: ${theme.dark ? "dark" : "light"};\n\n${declarations(generateRoles(theme))}\n}\n`;
  });
  const increased = themes.map(
    (theme) =>
      `[data-contrast="increased"][data-theme="${theme.id}"] {\n${declarations(generateIncreased(theme))}\n}\n`,
  );
  return `${HEADER}\n${blocks.join("\n")}\n/* The explicit preference and system \`prefers-contrast: more\` share this\n * resolved state: stronger text and control boundaries on each theme's own\n * surfaces and accent family. */\n${increased.join("\n")}`;
}
